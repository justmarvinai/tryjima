/**
 * How many templates the library ships.
 *
 * Derived from the duration table rather than from `templates` on purpose: the
 * registry pulls in Pixi and all 495 template modules (~2.7 MB), and the
 * landing page needs this number in three sentences of copy. Importing the
 * whole library to render "495" cost every first-time visitor the entire
 * template bundle before the hero had painted.
 *
 * `index.test.ts` asserts this equals `templates.length`, so a template added
 * without a duration entry fails the unit suite rather than quietly making the
 * marketing copy wrong.
 */
